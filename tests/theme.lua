local H = require("herde.ui.highlights")
local U = require("herde.ui.util")
H.setup()
assert(vim.api.nvim_get_hl(0, { name = "HerdeNormal", link = true }).link == "NormalFloat")
assert(vim.api.nvim_get_hl(0, { name = "HerdeBlocked", link = true }).link == "DiagnosticWarn")
vim.api.nvim_set_hl(0, "HerdeTitle", { link = "Special" })
H.setup()
assert(vim.api.nvim_get_hl(0, { name = "HerdeTitle", link = true }).link == "Special", "user highlights must survive setup")
vim.api.nvim_set_hl(0, "HerdeTitle", { link = "Title" })
assert(vim.fn.strdisplaywidth(U.clip("語語語語", 5)) <= 5, "labels must clip on display cells")
assert(not U.text("label\nnew\tfield"):find("[\n\t]"))
local buf = U.buf("theme")
local win = U.float(buf, "Theme", 40, 8, false, { footer = "search /   close q" })
local config = vim.api.nvim_win_get_config(win)
assert(config.footer and config.footer_pos == "left")
assert(vim.wo[win].winhighlight:find("NormalFloat:HerdeNormal", 1, true))
U.delete({ win = win, buf = buf })
print("theme and display checks passed")
