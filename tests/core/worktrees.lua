local root = vim.fn.tempname()
local original_cwd = vim.fn.getcwd()
vim.fn.mkdir(root .. "/checkout", "p")
vim.fn.mkdir(root .. "/state", "p")
vim.fn.writefile({ "first", "second" }, root .. "/checkout/file.lua")
vim.cmd("edit " .. vim.fn.fnameescape(root .. "/checkout/file.lua"))
vim.api.nvim_buf_set_lines(0, 1, 2, false, { "unsaved" })
local original_buf = vim.api.nvim_get_current_buf()
local original_tab = vim.api.nvim_get_current_tabpage()
local worktrees = require("herde.core.worktrees")
local opts = { state_dir = root .. "/state" }
local target, err
worktrees.open({ id = "w", path = root .. "/checkout" }, opts, function(e, tab) err, target = e, tab end)
assert(not err and target and target ~= original_tab)
assert(vim.api.nvim_buf_is_valid(original_buf) and vim.bo[original_buf].modified, "unsaved buffer survives")
assert(vim.api.nvim_tabpage_is_valid(original_tab), "original tab survives")
vim.cmd("edit " .. vim.fn.fnameescape(root .. "/checkout/file.lua"))
vim.api.nvim_win_set_cursor(0, { 2, 0 })
assert(worktrees.save_current(opts))
vim.api.nvim_set_current_tabpage(original_tab)
local count = #vim.api.nvim_list_tabpages()
worktrees.open({ id = "w", path = root .. "/checkout" }, opts, function(e, tab) assert(not e and tab == target) end)
assert(#vim.api.nvim_list_tabpages() == count, "existing workspace tab should be reused")
worktrees.open({ id = "remote", path = root .. "/checkout", remote = true }, opts, function(e) assert(e and e:find("remote")) end)
worktrees.open({ id = "missing", path = root .. "/missing" }, opts, function(e) assert(e and e:find("does not exist")) end)
worktrees.open({ id = "literal", path = "`echo invalid`" }, opts, function(e) assert(e and e:find("absolute")) end)
assert(#vim.api.nvim_list_tabpages() == count, "invalid paths must not alter topology")
vim.bo[original_buf].modified = false
vim.api.nvim_set_current_tabpage(original_tab)
vim.cmd("tcd " .. vim.fn.fnameescape(original_cwd))
vim.fn.delete(root, "rf")
print("worktree checks passed")
