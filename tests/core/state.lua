local function agent(id, state, workspace)
  return { id = id, name = id, workspace_id = workspace or "w", state = state, identity_stable = true }
end
local function snapshot(agents) return { workspaces = { { id = "w", name = "workspace" } }, agents = agents } end

local attention = require("herde.core.attention").new({ history_limit = 20 })
assert(#attention:update(snapshot({ agent("a", "idle"), agent("b", "blocked") })) == 0)
assert(#attention:list("active") == 1, "baseline blocked request must be visible")
attention:ack("b")
assert(#attention:list("active") == 1, "acknowledgement cannot answer a blocked request")
assert(#attention:update(snapshot({ agent("a", "working"), agent("b", "blocked") })) == 0)
local events = attention:update(snapshot({ agent("a", "done"), agent("b", "idle") }))
assert(#events == 1 and events[1].kind == "completed")
assert(#attention:update(snapshot({ agent("a", "done"), agent("b", "idle") })) == 0, "polls must deduplicate")
attention:ack("a")
assert(#attention:list("active") == 0)
attention:update(snapshot({ agent("a", "working") }))
assert(#attention:update(snapshot({ agent("a", "idle") }), true) == 0, "reconnection must rebaseline")
attention:update(snapshot({ agent("a", "working") }))
attention:update(snapshot({ agent("a", "unknown") }))
assert(#attention:list("active") == 0, "unknown alone must not imply completion")
assert(#attention:update(snapshot({ agent("a", "idle") })) == 1, "unknown must not erase observed working activity")
assert(#attention:update(snapshot({ agent("a", "idle") })) == 0, "working activity is consumed once")
local restored = require("herde.core.attention").new({}, {
  { id = "missing-event", agent_id = "gone", workspace_id = "w", kind = "blocked" },
  false, { kind = "invalid" },
})
restored:update(snapshot({ agent("a", "idle") }))
assert(#restored:list("active") == 0 and #restored:list("history") == 1, "missing persisted requests must resolve")
local scoped = require("herde.core.attention").new({ namespace = "herdr:default" }, {
  { id = "demo-event", agent_id = "demo/reviewer", workspace_id = "demo/main", kind = "blocked" },
  { id = "real-event", agent_id = "herdr:default/agent/reviewer", workspace_id = "w", kind = "blocked" },
})
assert(#scoped:list("active") == 1 and scoped:list("active")[1].id == "real-event", "demo requests must not appear as live Herdr attention")
assert(#scoped:serialize() == 2, "other backend history must remain available on disk")

local store = require("herde.core.store").new()
store:update(snapshot({ agent("a", "working"), agent("b", "idle") }))
assert(store:counts().working == 1)
local called = 0
local unsub = store:subscribe(function() called = called + 1 end)
store:select("b")
store.workspace_filter = "elsewhere"
store:select("b")
assert(store.workspace_filter == "w", "selecting across workspaces must reveal the selected agent")
unsub()
store:emit()
assert(called == 2)
store:update(snapshot({ agent("a-new", "idle") }))
assert(store.selected_id == "a-new", "vanished selection must recover")

store:update(snapshot({ agent("a", "idle"), agent("b", "idle") }))
local navigation = require("herde.core.navigation").new(store, { focus = function(_, _, cb) cb(nil, true) end }, attention)
navigation:select("b")
assert(navigation:previous().id == "a")
assert(navigation:previous().id == "b", "previous toggles live agents")
assert(navigation:cycle(1).id == "a")

local directory = vim.fn.tempname()
local persistence = require("herde.core.persistence").new({ state_dir = directory })
assert(persistence.writable)
local readonly = require("herde.core.persistence").new({ state_dir = directory })
assert(not readonly.writable and not readonly:save(), "concurrent writers must not overwrite")
local workspaces = require("herde.core.workspaces").new(store, persistence)
workspaces:label("a", "Fix retries")
workspaces:layout("w", { width = 41 })
persistence:close()
readonly:close()
local reopened = require("herde.core.persistence").new({ state_dir = directory })
assert(reopened.data.labels.a == "Fix retries" and reopened.data.layouts.w.width == 41)
reopened:close()
vim.fn.writefile({ vim.json.encode({ version = 1, labels = false, layouts = "bad", events = 12, muted = false }) }, directory .. "/metadata.json")
local corrupt = require("herde.core.persistence").new({ state_dir = directory })
assert(type(corrupt.data.labels) == "table" and type(corrupt.data.layouts) == "table")
assert(type(corrupt.data.events) == "table" and type(corrupt.data.muted) == "table")
corrupt:close()
local future_schema = vim.json.encode({ version = 2, labels = { a = "future" } })
vim.fn.writefile({ future_schema }, directory .. "/metadata.json")
local future = require("herde.core.persistence").new({ state_dir = directory })
assert(not future.writable and not future:save(), "unknown versions must never be overwritten")
future:close()
assert(vim.fn.readfile(directory .. "/metadata.json")[1] == future_schema)
vim.fn.delete(directory, "rf")
print("core state checks passed")
